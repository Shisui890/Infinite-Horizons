/**
 * Função utilitária para obter o perfil de mídia fotográfica de um corpo celeste.
 */
export function getCelestialRealMedia(bodyId: string): CelestialRealMediaProfile | null {
  // Aliases mapping
  const normalizedId = bodyId === 'proxima-centauri' ? 'proxima'
    : bodyId === 'cygnus-x1' ? 'cygnus_x1'
    : bodyId;

  return CELESTIAL_REAL_MEDIA[normalizedId] || null;
}
